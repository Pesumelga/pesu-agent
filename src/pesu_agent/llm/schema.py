"""Strict JSON Schema normalization for OpenAI / OpenRouter Structured Outputs.

This module provides normalization of Pydantic models and JSON Schema dicts into
strict Structured Outputs schemas complying with OpenAI/Azure gateway requirements:
- Every object schema explicitly has additionalProperties = False
- Every property in 'properties' is included in 'required'
- Original property declaration order is preserved (no arbitrary re-sorting)
- Optional / nullable types (e.g. anyOf with null) generated by Pydantic are preserved
- Array items, unions (anyOf), and intersections (allOf) are normalized recursively
- $defs references remain valid and $ref nodes with sibling keys are unraveled
- Self-contained implementation without depending on private SDK internals in production
"""

from __future__ import annotations

import copy
from typing import Any
from pydantic import BaseModel


def _resolve_json_ref(ref_str: str, root_dict: dict[str, Any]) -> dict[str, Any] | None:
    """Resolves a local JSON pointer (e.g. #/$defs/MyModel) against the root schema."""
    if not ref_str.startswith("#/"):
        return None
    parts = ref_str[2:].split("/")
    curr: Any = root_dict
    for p in parts:
        if isinstance(curr, dict) and p in curr:
            curr = curr[p]
        else:
            return None
    return curr if isinstance(curr, dict) else None


def normalize_strict_json_schema(
    schema_or_model: type[BaseModel] | dict[str, Any],
) -> dict[str, Any]:
    """Normalizes a Pydantic model or schema dictionary to be strict Structured Outputs compatible.

    Args:
        schema_or_model: Either a Pydantic BaseModel class or a raw JSON Schema dict.

    Returns:
        A deep-copied, strictly compliant JSON Schema dictionary.
    """
    if isinstance(schema_or_model, type) and issubclass(schema_or_model, BaseModel):
        raw_schema = schema_or_model.model_json_schema()
    elif isinstance(schema_or_model, dict):
        raw_schema = schema_or_model
    else:
        raise TypeError(
            f"normalize_strict_json_schema expects a BaseModel class or dict, got {type(schema_or_model)}"
        )

    root = copy.deepcopy(raw_schema)

    def _normalize_node(node: Any, path: tuple[str, ...]) -> Any:
        if not isinstance(node, dict):
            return node

        # 1. Normalize $defs / definitions recursively
        for defs_key in ("$defs", "definitions"):
            if defs_key in node and isinstance(node[defs_key], dict):
                for d_name, d_schema in node[defs_key].items():
                    _normalize_node(d_schema, (*path, defs_key, d_name))

        # 2. Object schema handling: apply additionalProperties=False & required
        # ONLY to actual object schemas (having 'properties' or explicit type == 'object')
        is_object = node.get("type") == "object" or "properties" in node
        if is_object:
            if node.get("type") != "object":
                node["type"] = "object"
            if node.get("additionalProperties") is not False:
                node["additionalProperties"] = False

            if "properties" in node and isinstance(node["properties"], dict):
                props = node["properties"]
                # Preserve exact property declaration order (do not sort alphabetically)
                node["required"] = list(props.keys())
                for k, v in props.items():
                    props[k] = _normalize_node(v, (*path, "properties", k))

        # 3. Arrays: normalize items recursively
        if "items" in node:
            if isinstance(node["items"], dict):
                node["items"] = _normalize_node(node["items"], (*path, "items"))
            elif isinstance(node["items"], list):
                node["items"] = [
                    _normalize_node(it, (*path, "items", str(i)))
                    for i, it in enumerate(node["items"])
                ]

        # 4. Unions: normalize anyOf branches recursively
        if "anyOf" in node and isinstance(node["anyOf"], list):
            node["anyOf"] = [
                _normalize_node(var, (*path, "anyOf", str(i)))
                for i, var in enumerate(node["anyOf"])
            ]

        # 5. Intersections: normalize allOf branches
        if "allOf" in node and isinstance(node["allOf"], list):
            if len(node["allOf"]) == 1 and isinstance(node["allOf"][0], dict):
                inner = _normalize_node(node["allOf"][0], (*path, "allOf", "0"))
                node.pop("allOf")
                node.update(inner)
            else:
                node["allOf"] = [
                    _normalize_node(entry, (*path, "allOf", str(i)))
                    for i, entry in enumerate(node["allOf"])
                ]

        # 6. oneOf branches
        if "oneOf" in node and isinstance(node["oneOf"], list):
            node["oneOf"] = [
                _normalize_node(var, (*path, "oneOf", str(i)))
                for i, var in enumerate(node["oneOf"])
            ]

        # 7. Strip None default (optional fields are already nullable via anyOf)
        if "default" in node and node["default"] is None:
            node.pop("default")

        # 8. Unravel $ref if adjacent sibling keys exist (strict draft-7 disallows siblings on $ref)
        ref = node.get("$ref")
        if ref and isinstance(ref, str) and len(node) > 1:
            resolved = _resolve_json_ref(ref, root)
            if resolved is not None:
                # Merge target into node while preserving node's own overrides
                merged = {**resolved, **node}
                merged.pop("$ref")
                node.clear()
                node.update(_normalize_node(merged, path))

        return node

    return _normalize_node(root, ())
