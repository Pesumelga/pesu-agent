    checks_with_ev = evaluator._evaluate_q2_04(
        gold=gold,
        workitems=[{"title": "로열티 요율", "status": "COMPLETED", "lifecycle_signal": "COMPLETION"}],
        answer="외부 8%, 내부 5%이며 내부 세무사는 대표 세무사 판단에 따라 예외적으로 조정 가능합니다.",
        claims=[],
        evidence=exception_evidence,
    )
    assert checks_with_ev["RETRIEVED_EXCEPTION_EVIDENCE_REFLECTED"] == "PASS"


