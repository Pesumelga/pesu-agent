def test_question_derived_anchors_survive_to_evidence_selector():
    """ANCHOR_TERMS_SURVIVE_PLAN_TO_SELECTOR = true.

    Verifies question-derived anchors flow through InvestigationPlan to EvidenceSelector
    and produce positive anchor matches on matching candidate evidence.
    """
    q2_02_path = Path("output/qualification_13_5d/v3_clean/clean_v3_run_20260917_231655/q2-02_production_result.json")
    assert q2_02_path.exists(), "Preserved Q3 raw artifact must exist offline"

    with open(q2_02_path, "r", encoding="utf-8") as f:
        q2_data = json.load(f)

    # Reconstruct offline candidates from preserved raw records
    candidates = []
    for q_idx, rec in enumerate(q2_data.get("raw_query_records", [])):
        for itm_idx, itm in enumerate(rec.get("raw_items", [])):
            candidates.append(EvidenceItem(
                evidence_id=f"ev_{q_idx}_{itm_idx}",
                source="slack",
                author=itm.get("sender_text") or "author",
                timestamp=itm.get("timestamp_raw") or "2026-09-17",
                text=itm.get("normalized_body") or "",
                permalink=itm.get("canonical_permalink") or "https://slack.com",
            ))

    cases_bundle = CleanPredeclarationLoader.load_production_cases()
    case_spec = cases_bundle["cases"][0]

    # Supply question-derived anchors
    question_anchors = ["지점 개설", "계약서", "검수"]
    plan, _, _ = build_production_investigation_plan(case_spec, anchor_terms=question_anchors)

    selector = EvidenceSelector(max_evidence_items=5)
    pkg, stats = selector.select_and_package(candidates=candidates, plan=plan)

    assert len(pkg.evidence_items) > 0
    # At least one selected evidence item must have matched question-derived anchors
    max_matches = max(item.anchor_match_count for item in pkg.evidence_items)
    assert max_matches > 0, "Question-derived anchors must match candidates and survive into EvidenceSelector"


